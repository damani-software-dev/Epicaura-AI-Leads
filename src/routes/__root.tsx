function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AuthGate />
      <Toaster position="bottom-right" />
    </QueryClientProvider>
  );
}

// Sign-in gate: `/` is the sign-in screen itself, so the first page a
// signed-out visitor sees is always the form. Protected paths wait for
// localStorage hydration, then bounce to sign-in — showing a neutral splash
// meanwhile so workspace content never flashes before the session is known.
function AuthGate() {
  const signedIn = useApp((s) => s.signedIn);
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const [hydrated, setHydrated] = useState(false);

  useEffect(() => {
    hydrateStore();
    setHydrated(true);
  }, []);

  if (pathname === "/") {
    if (hydrated && signedIn) return <Navigate to="/overview" replace />;
    return <Outlet />;
  }
  if (!hydrated) return <BootSplash />;
  if (!signedIn) return <Navigate to="/" replace />;

  return (
    <AppShell>
      <Outlet />
    </AppShell>
  );
}

function BootSplash() {
  return (
    <div className="flex min-h-screen items-center justify-center bg-background">
      <div className="flex flex-col items-center gap-3">
        <span className="flex size-9 animate-pulse items-center justify-center rounded-lg bg-foreground text-xs font-bold tracking-tight text-background">
          EA
        </span>
        <p className="text-xs text-muted-foreground">Loading workspace…</p>
      </div>
    </div>
  );
}
